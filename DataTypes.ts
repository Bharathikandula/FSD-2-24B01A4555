// string datatype
let str1 = "JavaScript";
console.log(str1);
let str2 = "Learning is fun";
console.log(str2);
let str3 = "Welcome!";
console.log(str3 + "\n");

// number datatype
let int1 = 45;
console.log(int1);
let int2 = 78;
console.log(int2);
let int3 = 999;
console.log(int3 + "\n");

// boolean datatype
let bool1 = false;
console.log(bool1);
let bool2 = true;
console.log(bool2);
let bool3 = 20 < 15;
console.log(bool3 + "\n");

// null datatype
let null1 = null;
console.log(null1 + "\n");

// bigint datatype
let big1 = 98765432109876543210n;
console.log(big1);
let big2 = 12345678987654321098n;
console.log(big2);
let big3 = 88888888888888888888n;
console.log(big3 + "\n");

// symbol datatype
let sym1 = Symbol("student");
console.log(sym1);
let sym2 = Symbol("course");
console.log(sym2);
let sym3 = Symbol("rollNo");
console.log(sym3);